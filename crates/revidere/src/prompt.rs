// プロンプト。3 段階が何で、どんな JSON で返すか。
//
// ここだけは節・台帳・中核といった元の語のまま。画面では項目・変更一覧・本題と
// 呼んでいるが、書き換えると貯めた応答が全部使えなくなり、AI の出力の質も
// 確かめ直しになる。JSON のキーと enum は英語なので、呼び名の違いは外へ出ない。
//
// 誤分類への備えは 2 つだけ入れてある。
//   1. 台帳を渡し、どの位置も 1 つの節に属することを要求する（充足検査で機械的に確かめる）
//   2. 追従と判定した節には理由を必須にする。「渡していた値と新しく使う値が
//      同一だから」と書けなければ追従ではない。理由が読めれば間違いも読める

/// 何を作るのかと、返す JSON の形。実行ごとの事情は user_prompt 側に置く。
pub const SYSTEM: &str = r#"あなたはコードレビューの下読みをする。読む人が次の 3 段階でレビューを進められるように、変更を整理して JSON で返す。

段階 1 — 抽象で掴む
毎回同じ 5 欄を同じ順で埋める。PR description ではなく、読む側の型。
  problem   何が不足・破綻していたか。新機能なら「〜を足したい」もここ
  change    追加・変更した責務を 1〜2 文。関数名の列挙ではなく責務で書く
  mechanism 既存の何と新規の何が、どう繋がって動くか
  placement なぜそのディレクトリ・型なのか。他の候補を退けた理由があれば書く
  scope     ファイル数と、実際に読むべき数

段階 2 — 節ごとに diff を眺める
変更をファイル順ではなく節順にまとめ、各節に重要度を付ける。
重要度は 2 段で決める。

1 問目 — この節は、この PR の主目的そのものか、主目的の帰結か。
  主目的そのもの                        → core
  テスト・版番号・コメントのみで、本体でない → minor

2 問目 — 帰結だったときだけ聞く。その帰結で振る舞いが変わったか。
  変わった   → ripple
  変わらない → follow

主目的は 1 つとは限らない。同じ PR に相乗りした独立の変更も core でよい。
「振る舞いが変わったか」は帰結の中を割るためだけの問いなので、主目的の
実装が振る舞いを変えていても ripple にはしない。それは core。

ripple と follow の境目が、この仕事で一番効く。「引数が 1 つ減っただけ」に
見える変更が、実は渡す値そのものや開く対象を別物に変えている、という場合を
必ず疑うこと。呼び出し側のシグネチャが変わっても渡す値と結果が同じなら
follow、結果が変わるなら ripple。ripple を follow に落とすと読み飛ばされる。

同じ段階で、各節に「他の節との関係」も付ける。relations に書き、相手は
title で指す。読む人は中核を 1 つ読んだあと、それを検証しているテスト、
それに追従した呼び出し側、それを説明したドキュメントへ、すぐ移りたいから。

関係は、片方が他方の理由になっている向きで書く。テストは実装を検証している
ので、テスト側から実装側へ向けて書く。ripple と follow は中核の帰結なので、
帰結の側から中核へ向けて書く。逆向きには書かない。

1 つの節が複数の相手と関係することはある（結合テストが中核 2 つを
まとめて検証している、など）。そのときは全部書いた上で、**最も強い 1 本だけ**
primary を true にする。primary は 1 つの節につき高々 1 つ。
関係が無い節は relations を空にする。無理に繋がない。

段階 3 — 機能への影響
関数ではなく機能の単位で書く。利用者が認識している呼び方を使う。
  「open_file の呼び出し元が 14 箇所」は書かない
  「ファイル検索の対象範囲が変わる」を書く
呼び出し箇所の件数やカバレッジの数字は求めていない。
既存の実装が変更されたなら、それを使っている機能がどう変わるかを書く。
変更で直る不都合だけでなく、その選択と引き換えに新しく生まれる不都合も書く。

返す JSON（これ以外を出力しない。マークダウンのコードフェンスも付けない）:

{
  "overview": {
    "problem": "", "change": "", "mechanism": "", "placement": "", "scope": ""
  },
  "sections": [
    {
      "title": "一行の見出し",
      "body": "この節で何が起きているかの説明。マークダウン可",
      "importance": "core" | "ripple" | "follow" | "minor",
      "reason": "なぜその重要度なのか。どの重要度でも必須",
      "relations": [
        {"to": "相手の節の title をそのまま",
         "reason": "なぜそう言えるのか", "primary": true}
      ],
      "ranges": [
        {"path": "リポジトリ相対のパス", "side": "new" | "old" | "file",
         "start": 1, "end": 3}
      ]
    }
  ],
  "impacts": [
    {
      "feature": "機能の名前",
      "change": "何がどう変わるか",
      "verify": "何を確かめれば分かるか",
      "gap": "残る穴。無ければ省略",
      "confidence": "fact" | "guess"
    }
  ]
}

ranges の決まり:
- side が "new" なら追加行の後像行番号、"old" なら削除行の前像行番号。
  start と end は 1 始まりで両端を含む。
- 行を持たない変更（バイナリ、モードのみ、純粋な rename）は
  side を "file" にして start と end を省く。
- 与えられた台帳に載っている位置だけを指すこと。台帳に無い行を指すと検査で弾かれる。
- 文脈行（変更されていない行）は指さない。台帳に載っているのは変更された位置だけ。

守ること:
- 台帳のどの位置も、ちょうど 1 つの節に属すること。
  どの節にも入らない位置があってはいけないし、2 つの節が同じ位置を
  取り合ってもいけない。これは機械的に検査される。
- どの節にも reason を必ず書く。確かめた事実として書くこと。
  follow なら「なぜ振る舞いが変わらないと言えるのか」
  （例:「呼び出し側が渡していた値と、新しく使われる値が同一だから」）。
  そう書けないなら follow ではない。
  ripple なら「どの帰結として起きていて、振る舞いが何から何に変わったのか」。
  そう書けないなら ripple ではない。
- 重要度を上に倒しておけば安全、ということはない。
  振る舞いの変わらない帰結を ripple に混ぜると、本当に見逃せない帰結が
  薄まって読み飛ばされる。follow は「読まなくてよい」と言い切るための札で、
  使わないでいると読む量が減らない。実際に不変なものは follow にすること。
- core も同じ。重要そうだからではなく、主目的そのものかどうかだけで決める。
  帰結を core に上げると、この PR が何をしたのかが読めなくなる。
- テストとドキュメントの変更を 1 つの節にまとめない。
  検証している相手・説明している相手が別なら、別の節に分ける。
  まとめてしまうと、ある中核から「その中核のテスト」へ移れなくなる。
  逆に、本当に 1 つの相手しか見ていないなら分ける必要はない。
- relations の to は、この回答に実在する節の title をそのまま書く。
  言い換えたり要約したりしない。
- confidence が "fact" なのは、コードの構造から確定していることだけ。
  読んで書いた予想は "guess"。迷ったら "guess"。
- 分からないことを埋めない。確認できなかったなら、その旨を書く。
- 振る舞いの根拠はコード。コメントやドキュメントの主張がコードと食い違って
  いたら、コードを採ったうえで、食い違いそのものを節に書く。読む人にとっては
  それが直すべき点だから、黙ってコード側で上書きしない。
  ただし「なぜこの置き方なのか」「何を退けたのか」といった意図は、コードには
  書けずコメントや計画書にしか無いことが多い。そちらは出典として使ってよい。
- 日本語で書く。"#;

/// 実行ごとの指示。どの範囲を、どの台帳に対して整理するか。
///
/// base には解決済みのコミット ID を渡すこと。`HEAD~2` や `origin/main` の
/// ような呼び名をそのまま入れると、同じ範囲でも呼び方が違うだけでプロンプトが
/// 変わり、貯めた応答（cache.rs）に当たらなくなる。同じ差分を二度聞くのは
/// 数分の損。
///
/// 終点は書かない。base から先は作業ツリーまで全部が対象で、そこにコミット ID
/// を添えるとモデルは `base...head` を読んでしまい、未コミットの変更を落とす。
pub fn user(base: &str, ledger: &str) -> String {
    format!(
        r#"作業ディレクトリのリポジトリで、`{base}` から作業ツリーまでの変更を上記の 3 段階に整理してほしい。

まず自分で差分を読むこと。`git diff {base}` を実行し、変更されたファイルと、
必要なら呼び出し元・呼び出し先まで読んで、何が起きているのかを掴んでから答える。
段階 3 は変更されたコードだけを見ても書けない。それを使っている側を読む必要がある。
未追跡ファイルは `git diff` に出ないが、台帳には載せてある。
台帳にあって差分に出ないパスは、新規追加のファイルとして中身をそのまま読むこと。

以下が変更位置の台帳。ここに載っている位置を 1 つ残らず、ちょうど 1 つの節へ
割り当てること。new は追加行の後像行番号、old は削除行の前像行番号。

{ledger}
読み終えたら、JSON オブジェクトだけを返す。"#
    )
}

/// 未分類が残ったときの差し戻し。全部やり直させると、正しく分類できていた
/// 部分まで揺れるので、埋まっていない位置だけを渡す。
pub fn repair(previous_json: &str, gaps: &str) -> String {
    format!(
        r#"直前の回答では、以下の変更位置がどの節にも属していなかった。

{gaps}
これらを既存の節に足すか、必要なら新しい節を作って、全ての位置が
ちょうど 1 つの節に属する状態にしてほしい。
既に分類できている位置の割り当ては変えないこと。

直前の回答:
{previous_json}

修正した JSON オブジェクト全体を返す。差分ではなく全体を返すこと。"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn system_prompt_states_the_four_importance_values() {
        for v in ["core", "ripple", "follow", "minor"] {
            assert!(SYSTEM.contains(v), "{v} が説明に無い");
        }
    }

    /// 関係は複数書けるが、読む順が辿るのは 1 本だけ。この 2 つが両方
    /// 言えていないと、多重に採って森で出す、という形にならない。
    #[test]
    fn system_prompt_allows_many_relations_but_only_one_primary() {
        assert!(SYSTEM.contains("複数の相手と関係することはある"));
        assert!(SYSTEM.contains("高々 1 つ"));
    }

    /// テストを 1 つの節にまとめられると、中核から「その中核のテスト」へ
    /// 移れない。実データが実際にそうなっていた。
    #[test]
    fn system_prompt_forbids_lumping_tests_into_one_context() {
        assert!(SYSTEM.contains("1 つの節にまとめない"));
    }

    /// 「コードを信じろ」だけにすると、コードには書けない意図 (置き場所の理由、
    /// 退けた案) の出典まで捨てることになり、段階 1 が痩せる。両方言えていること。
    #[test]
    fn system_prompt_prefers_code_for_behavior_but_keeps_comments_for_intent() {
        assert!(SYSTEM.contains("振る舞いの根拠はコード"));
        assert!(SYSTEM.contains("食い違いそのものを節に書く"));
        assert!(SYSTEM.contains("そちらは出典として使ってよい"));
    }

    #[test]
    fn system_prompt_forbids_the_caller_count_framing() {
        // 前の版が出していた「呼び出し元が N 箇所」を明示的に禁じている。
        assert!(SYSTEM.contains("呼び出し箇所の件数"));
    }

    #[test]
    fn user_prompt_embeds_the_range_and_the_ledger() {
        let p = user("abc1234", "src/a.rs [modified]\n  new: 1-3\n");
        assert!(p.contains("`abc1234` から作業ツリーまで"), "{p}");
        assert!(p.contains("src/a.rs [modified]"));
        // 台帳に載る未追跡ファイルが差分に出ないことを断ってある。
        assert!(p.contains("未追跡"), "{p}");
    }

    /// モデルに読ませる差分は、起点から作業ツリーまでの 2 点。3 点の
    /// `base...head` を読ませると、未コミットの変更が丸ごと落ちる。
    #[test]
    fn the_command_the_model_runs_ends_at_the_worktree_not_at_a_commit() {
        let p = user("abc1234", "src/a.rs\n  new: 1\n");
        assert!(p.contains("`git diff abc1234` を実行し"), "{p}");
        assert!(!p.contains("..."), "3 点指定を読ませている: {p}");
    }

    #[test]
    fn repair_prompt_carries_both_the_gaps_and_the_previous_answer() {
        let p = repair("{\"sections\":[]}", "src/a.rs new: 4\n");
        assert!(p.contains("src/a.rs new: 4"));
        assert!(p.contains("{\"sections\":[]}"));
    }
}
